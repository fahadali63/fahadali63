export const MAIN = { x: 36, y: 62, w: 640, h: 610 };
export const RIGHT = { x: 700, y: 40, w: 236 };
const lvlName = (n) => ['', 'First', 'Second', 'Third', 'Fourth', 'Fifth', 'Sixth', 'Seventh', 'Eighth', 'Ninth', 'Tenth', 'Eleventh', 'Twelfth'][n] || `Level ${n}`;
export { lvlName };

/** Common floor-plan viewport: returns { sheet, vp, prims } */
export function planSheet(disc, number, title, fl, ctx, o = {}) {
  const sh = new Sheet(disc, number, title);
  const { W, D } = ctx.layout;
  const sc = fitScale(W + 24, D + 20, MAIN);
  const prims = planBase(fl, ctx.layout, { fill: o.fill, thin: o.thin, corridorFill: o.corridorFill });
  if (o.tags !== false) prims.push(...roomTags(fl, { s: sc.s, label: o.label, second: o.second, skip: o.skip }));
  if (o.dims !== false) prims.push(...outerDims(W, D));
  return { sh, prims, W, D, fl, sc };
}
export function finishPlan(ps, sheetTitle, num = '1') {
  const vp = ps.sh.view(ps.prims, ps.W, ps.D, MAIN, { pad: 10, vcenter: true });
  ps.sh.add([...viewTitle(MAIN.x, 38, num, sheetTitle, vp.label), ...northArrow(MAIN.x + MAIN.w - 14, 44)]);
  return vp;
}

